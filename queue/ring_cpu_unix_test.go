package queue

import (
	"syscall"
	"time"
)

// processCPUTime reports the CPU time consumed by this process so far.  The
// second return value is false on platforms where this cannot be measured, in
// which case callers should skip CPU-based assertions.
func processCPUTime() (time.Duration, bool) {
	var ru syscall.Rusage
	if err := syscall.Getrusage(syscall.RUSAGE_SELF, &ru); err != nil {
		return 0, false
	}
	return time.Duration(ru.Utime.Nano() + ru.Stime.Nano()), true
}
